import QRCode from "qrcode";

// ============================================================
// صورة QR الفاتورة (PNG بدقة عالية)
// - QR المرحلة التانية كبير جداً (توقيع + مفتاح عام + شهادة ≈ 600-800 حرف)
//   فبيترسم بدقة عالية: كل مربع في الكود = 10 بكسل بالظبط (scale)
//   عشان يفضل حاد لما يتصغّر في الطباعة
// - مستوى تصحيح L = مربعات أقل وأكبر (أسهل في القراءة)
// - margin 2: فراغ أبيض حوالين الكود (لازم للقراءة)
// - PNG (مش SVG): بيطلع صح في الطباعة وفي تحويل الصفحة لـ PDF
//   (رسم الـ PDF مابيعرفش يرسم صور SVG فكان الـ QR بيطلع فاضي/مقصوص)
// ============================================================
export function qrDataUrl(value) {
  return QRCode.toDataURL(value, {
    errorCorrectionLevel: "L",
    margin: 2,
    scale: 10,
    color: { dark: "#000000", light: "#ffffff" },
  });
}
